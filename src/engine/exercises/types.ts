// Общее описание упражнения: чем его мерить, какие суставы нужны, какие пороги у счётчика.
// Упражнение = измеритель (кадр → метрики и прогресс) + пороги автомата + правила ошибок.

import type { PoseFrame } from '../geometry';
import type { RuleDef } from '../rules';
import type { ExerciseId, Phase, Side } from '../types';
import type { FsmThresholds } from './fsm';

export interface BaseMetrics {
  /** 0 — исходное положение, 1 — полная амплитуда, больше 1 — ещё глубже/выше. */
  progress: number;
  /**
   * Измеритель знает точнее счётчика: человек уже вернулся в исходное положение — повтор закрыть сейчас,
   * даже если прогресс ещё не упал (бёрпи: встал и сразу пошёл вниз, не прыгнув, — иначе ожидание прыжка
   * склеивало два бёрпи в одно).
   */
  returned?: boolean;
  /**
   * Это движение засчитывать нельзя (удар раскрытой ладонью): счётчик закроет его как попытку, а не повтор,
   * правила на попытке скажут почему.
   */
  veto?: boolean;
  /** Какую кисть проверять на кулак в этом движении (бокс — бьющую); нет — обе. */
  hand?: Side;
  /**
   * Движение оказалось не тем упражнением (подтягивания: руки ушли с перекладины, встал на пол) — текущий
   * повтор отменить без засчёта, а не закрыть возвратом прогресса к нулю.
   */
  abort?: boolean;
}

export interface ExerciseMeter<M extends BaseMetrics> {
  /**
   * Метрики кадра или null, если нужные суставы не видны.
   * phase — текущая фаза счётчика: в исходном положении измеритель обновляет эталон «стоя».
   */
  measure(frame: PoseFrame, phase: Phase): M | null;
  reset(): void;
}

export interface ExerciseDef<M extends BaseMetrics = BaseMetrics> {
  id: ExerciseId;
  /** Суставы, без которых упражнение не измерить: пропали — пауза и подсказка вернуться в кадр. */
  requiredJoints: readonly number[];
  /** Руки над головой — часть упражнения: жест «обе руки вверх» на подходе отключается. */
  armsOverhead: boolean;
  fsm: FsmThresholds;
  createMeter(): ExerciseMeter<M>;
  /** Правила ошибок: код из каталога hints.ts + проверка. Текст, суставы, фазы, важность — из каталога. */
  rules: readonly RuleDef<M>[];
  /**
   * Упражнение на две стороны: какая сторона работала в этом движении (по метрикам нижней точки).
   * Если задано, повтор засчитывается парой — левая + правая сторона; одна сторона — событие half_rep.
   */
  sideOf?(bottom: M): Side | null;
  /**
   * Упражнение на время (планка): повтор — секунда в правильном положении (прогресс ≥ 1), targetReps — секунды.
   * Счётчик повторов не используется; ошибки секунды снижают её оценку.
   */
  hold?: boolean;
  /**
   * Измеритель сам отбрасывает кадры-сбои, общий фильтр правдоподобия (PoseGate) не нужен. Отжимания и планка
   * лицом к камере: корпус в кадре сжат перспективой и за спуск укорачивается вдвое — фильтр по длине корпуса
   * принимал спуск за «телепорт» и выкидывал весь низ отжимания (E-31).
   */
  ownGate?: boolean;
  /** Упражнение на турнике: движок ищет перекладину у кистей по пикселям кадра (frame.bar, bar.ts). */
  needsBar?: boolean;
  /** Подсказка, когда нужных суставов не видно (по умолчанию — «встань так, чтобы тебя было видно целиком»). */
  lostHint?: string;
  /** Упражнению нужны кисти (кулак или ладонь, hands.ts): движок проверяет их, пока идёт движение. */
  hands?: boolean;
}
